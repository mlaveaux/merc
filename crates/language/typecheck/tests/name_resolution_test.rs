//! Resolution of sort names and of equation variables by [DataSpecification::from_untyped].

use std::hash::DefaultHasher;
use std::hash::Hash;
use std::hash::Hasher;

use merc_syntax::ConstructorId;
use merc_syntax::DataExpr;
use merc_syntax::DataExprKind;
use merc_syntax::EqnSpecId;
use merc_syntax::EquationId;
use merc_syntax::MapId;
use merc_syntax::OffsetSpans;
use merc_syntax::SortExpressionKind;
use merc_syntax::UntypedDataSpecification;
use merc_typecheck::DataSpecification;
use merc_typecheck::WellTypedError;

fn typed(text: &str) -> DataSpecification {
    DataSpecification::from_untyped(UntypedDataSpecification::parse(text).unwrap()).unwrap()
}

fn typecheck_err(text: &str) -> WellTypedError {
    match DataSpecification::from_untyped(UntypedDataSpecification::parse(text).unwrap()) {
        Err(err) => err,
        Ok(_) => panic!("expected {text} to be rejected"),
    }
}

#[test]
#[cfg_attr(miri, ignore)] // Test is too slow under miri
fn test_identical_duplicate_sort_is_deduplicated() {
    // As in mCRL2.
    typed("sort D = List(Bool);\nsort D = List(Bool);");
}

#[test]
#[cfg_attr(miri, ignore)] // Test is too slow under miri
fn test_conflicting_duplicate_sort_is_rejected() {
    let text = "sort D = List(Bool); sort D = List(Nat);";
    match typecheck_err(text) {
        WellTypedError::DuplicateSortDeclaration { sort, span } => {
            assert_eq!(sort, "D");
            // The second declaration is blamed.
            assert_eq!(span.start, text.rfind('D').unwrap());
        }
        other => panic!("unexpected error {other:?}"),
    }
}

/// Binder sorts inside equation bodies are resolved, not just declaration-level sorts.
#[test]
#[cfg_attr(miri, ignore)] // Test is too slow under miri
fn test_equation_body_binder_sorts_are_resolved() {
    let spec = typed("sort D = struct d1 | d2; map f: D -> Bool; var x: D; eqn f(x) = forall y: D. y == x;");
    let equation = &spec.data_specification().equation_declarations[0];
    let d = *spec.sorts().index("D").unwrap();

    let SortExpressionKind::Resolved(name, id) = &equation.variables[0].sort.node else {
        panic!("expected a resolved sort, got {:?}", equation.variables[0].sort);
    };
    assert_eq!((name.as_str(), **id), ("D", d));

    let DataExprKind::Quantifier { variables, .. } = &equation.equations[0].rhs.node else {
        panic!("expected a quantifier body, got {:?}", equation.equations[0].rhs);
    };
    let SortExpressionKind::Resolved(name, id) = &variables[0].sort.node else {
        panic!("expected a resolved sort, got {:?}", variables[0].sort);
    };
    assert_eq!((name.as_str(), **id), ("D", d));
}

#[test]
#[cfg_attr(miri, ignore)] // Test is too slow under miri
fn test_undeclared_binder_sort_is_rejected() {
    let text = "map s: Set(Nat); eqn s = { n: Undeclared | true };";
    match typecheck_err(text) {
        WellTypedError::UndefinedSort { sort, span } => {
            assert_eq!(sort, "Undeclared");
            assert_eq!(&text[span.start..span.end], "Undeclared");
        }
        other => panic!("unexpected error {other:?}"),
    }
}

/// Constructor and map declarations get their own ids, also the constructors generated by struct
/// desugaring; equation blocks get an id, and equations one local to their block.
#[test]
#[cfg_attr(miri, ignore)] // Test is too slow under miri
fn test_declarations_get_distinct_ids() {
    let spec = typed(
        "sort D = struct c1 | c2;
         map f: D -> Bool;
             g: D -> Bool;
         var x: D;
         eqn f(x) = true;
             g(x) = false;
         var y: D;
         eqn f(y) = g(y);",
    );
    let data = spec.data_specification();

    let constructor_ids: Vec<_> = data.constructor_declarations.iter().map(|decl| decl.id).collect();
    assert_eq!(
        constructor_ids,
        vec![Some(ConstructorId::new(0)), Some(ConstructorId::new(1))]
    );
    let map_ids: Vec<_> = data.map_declarations.iter().map(|decl| decl.id).collect();
    assert_eq!(map_ids, vec![Some(MapId::new(0)), Some(MapId::new(1))]);

    let equation_ids = |block: usize| -> (Option<EqnSpecId>, Vec<Option<EquationId>>) {
        let block = &data.equation_declarations[block];
        (block.id, block.equations.iter().map(|eqn| eqn.id).collect())
    };
    assert_eq!(
        equation_ids(0),
        (
            Some(EqnSpecId::new(0)),
            vec![Some(EquationId::new(0)), Some(EquationId::new(1))]
        )
    );
    assert_eq!(
        equation_ids(1),
        (Some(EqnSpecId::new(1)), vec![Some(EquationId::new(0))])
    );
}

/// Whether `expr` is the variable `name` resolved to the declaration with `var_id`.
fn resolves_to(expr: &DataExpr, name: &str, var_id: merc_syntax::VarId) -> bool {
    matches!(&expr.node, DataExprKind::Resolved(actual, id) if actual == name && **id == var_id)
}

#[test]
#[cfg_attr(miri, ignore)] // Test is too slow under miri
fn test_equation_variables_resolve_to_their_var_block_declaration() {
    let spec = typed("map f: Bool -> Nat; var x: Bool; eqn x -> f(x) = 0;");
    let block = &spec.data_specification().equation_declarations[0];
    let declared = block.variables[0].var_id.expect("the variable was assigned a VarId");
    let equation = &block.equations[0];

    assert!(resolves_to(equation.condition.as_ref().unwrap(), "x", declared));
    let DataExprKind::Application { arguments, .. } = &equation.lhs.node else {
        panic!("expected an application, got {:?}", equation.lhs);
    };
    assert!(resolves_to(&arguments[0], "x", declared));
}

/// The variables of two `var` blocks get distinct ids, and each block's equations see their own.
#[test]
#[cfg_attr(miri, ignore)] // Test is too slow under miri
fn test_variable_scope_does_not_leak_across_var_blocks() {
    let spec = typed("map f: Nat -> Nat; g: Bool -> Bool; var x: Nat; eqn f(x) = x; var y: Bool; eqn g(y) = y;");
    let blocks = &spec.data_specification().equation_declarations;
    let x = blocks[0].variables[0].var_id.unwrap();
    let y = blocks[1].variables[0].var_id.unwrap();
    assert_ne!(x, y);
    assert!(resolves_to(&blocks[0].equations[0].rhs, "x", x));
    assert!(resolves_to(&blocks[1].equations[0].rhs, "y", y));
}

/// Rebasing a resolved tree moves every declaration span, but leaves its expressions equal to,
/// and hashing the same as, the originals.
#[test]
#[cfg_attr(miri, ignore)] // Test is too slow under miri
fn test_rebased_resolved_expression_keeps_its_identity() {
    let spec = typed("map f: Nat -> Nat; var n: Nat; eqn f(n) = n;");
    let original = spec.data_specification().clone();
    let mut rebased = original.clone();
    rebased.offset_spans(100);

    let original = &original.equation_declarations[0].equations[0].rhs;
    let shifted = &rebased.equation_declarations[0].equations[0].rhs;
    let (DataExprKind::Resolved(_, before), DataExprKind::Resolved(_, after)) = (&original.node, &shifted.node) else {
        panic!("expected the right-hand side to resolve to the equation variable");
    };
    assert_eq!(after.span.start, before.span.start + 100);

    assert_eq!(original, shifted);
    let hash = |expr: &DataExpr| {
        let mut hasher = DefaultHasher::new();
        expr.hash(&mut hasher);
        hasher.finish()
    };
    assert_eq!(hash(original), hash(shifted));
}
